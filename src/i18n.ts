/**
 * Lightweight placeholder substitution. Supports {name}-style tokens.
 *
 * Unknown tokens are left intact — the literal braces cannot appear in our
 * translated strings, so a leftover {x} on screen is a clear signal that a
 * string was missed at translation time.
 */
function fillTemplate(s: string, vars: Record<string, string | number> = {}): string {
  return s.replace(/\{(\w+)\}/g, (_m, k: string) =>
    vars[k] !== undefined ? String(vars[k]) : `{${k}}`);
}

function resolver(): ((k: string, vars?: Record<string, string | number>) => string) | undefined {
  return (globalThis as unknown as { __tResolver?: (k: string, vars?: Record<string, string | number>) => string }).__tResolver;
}

/**
 * The translation function. Throws if the resolver is missing — silent fallback
 * to the key would mask missing translations under the inlined EN default.
 */
export function t(key: string, vars?: Record<string, string | number>): string {
  const r = resolver();
  if (r === undefined) {
    throw new Error('i18n: __tResolver not installed');
  }
  return r(key, vars);
}

/**
 * Optional: walk the DOM and translate any element whose dataset.i18n matches
 * a known key. Kept for completeness; current call sites pass t() into the
 * builders instead.
 */
export function applyStatic(root: ParentNode): void {
  const r = resolver();
  if (!r) return;
  for (const node of root.querySelectorAll<HTMLElement>('[data-i18n]')) {
    const key = node.dataset.i18n;
    if (!key) continue;
    setText(node, r(key));
  }
}

// Module-side-effect: install the resolver *here*, before any sibling UI module
// is even imported. UI modules have top-level `const FOO = [t('…')]` literals
// that run at module-eval time; if i18n.ts is imported anywhere on the chain
// before them, this side-effect is live by the time the literals fire.
(globalThis as unknown as { __tResolver: (k: string, vars?: Record<string, string | number>) => string }).__tResolver = (
  key: string,
  vars?: Record<string, string | number>,
): string => {
  const g = globalThis as unknown as { __koDict?: Record<string, string>; __enDict?: Record<string, string> };
  const ko = g.__koDict ?? KO;
  const en = g.__enDict ?? EN;
  const base = (ko[key] !== undefined ? ko[key] : en[key] !== undefined ? en[key] : key);
  return fillTemplate(base, vars);
};
(globalThis as unknown as { __koDict: Record<string, string> }).__koDict = KO;
(globalThis as unknown as { __enDict: Record<string, string> }).__enDict = EN;
(globalThis as unknown as { __currentLang: string }).__currentLang = 'ko';
